-- Seasons: time-boxed focus periods. A season gives existing Domains a role,
-- Focus (the main attention) or Passive (still active, not the priority);
-- domains left out are resting. Purely additive: two new tables, no changes to
-- existing ones. Safe to re-run.
--
-- Run on mrtn-psql itself (the repo isn't there, so copy this file over first:
--   scp SQL/create_seasons_tables.sql matt@10.0.0.225:~/ ). pg_hba only allows
-- kc_user over localhost on that box, so use -h localhost, not its IP.
-- Back up first:
--   pg_dump -h localhost -U kc_user -d kc_db -Fc -f ~/kc_db_backup_YYYYMMDD.dump
-- Apply:
--   psql -h localhost -U kc_user -d kc_db -f ~/create_seasons_tables.sql

CREATE TABLE IF NOT EXISTS "Seasons" (
    "SeasonId" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" VARCHAR(100) NOT NULL,
    "Intention" TEXT NULL,
    -- Stored, not derived from the dates: a season only rotates when it's
    -- ended on purpose, so running past PlannedEnd just shows it as overdue.
    "Status" VARCHAR(20) NOT NULL DEFAULT 'Planned',
    "PlannedStart" DATE NOT NULL,
    "PlannedEnd" DATE NOT NULL,
    -- Actual start/end, set by the lifecycle endpoints. Stats use these.
    "StartedAt" TIMESTAMP NULL,
    "EndedAt" TIMESTAMP NULL,
    "Reflection" TEXT NULL,
    -- Why the season has more than two Focus domains, written when the
    -- overload warning was confirmed. Cleared once it's back to two or fewer.
    "OverloadReason" TEXT NULL,
    "CreatedAt" TIMESTAMP NOT NULL DEFAULT now(),
    "UpdatedAt" TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT "CK_Seasons_Status" CHECK ("Status" IN ('Planned', 'Active', 'Ended')),
    CONSTRAINT "CK_Seasons_PlannedRange" CHECK ("PlannedEnd" > "PlannedStart"),
    -- Seasons never overlap: at most one is Active. An exclusion constraint
    -- rather than a partial unique index so it can be deferred, which lets a
    -- rotate end the current season and start the next in one UPDATE.
    CONSTRAINT "EX_Seasons_OneActive" EXCLUDE USING btree ("Status" WITH =)
        WHERE ("Status" = 'Active') DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE IF NOT EXISTS "SeasonDomains" (
    "SeasonId" INTEGER NOT NULL,
    "DomainId" INTEGER NOT NULL,
    "Role" VARCHAR(20) NOT NULL,
    "Note" VARCHAR(300) NULL,
    -- Deferred so a lineup can be replaced (delete + insert) in one statement.
    CONSTRAINT "PK_SeasonDomains" PRIMARY KEY ("SeasonId", "DomainId") DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT "CK_SeasonDomains_Role" CHECK ("Role" IN ('Focus', 'Passive')),
    CONSTRAINT "FK_SeasonDomains_Seasons" FOREIGN KEY ("SeasonId")
        REFERENCES "Seasons" ("SeasonId") ON DELETE CASCADE,
    -- Deleting a domain drops it from every season instead of being blocked.
    CONSTRAINT "FK_SeasonDomains_Domains" FOREIGN KEY ("DomainId")
        REFERENCES "Domains" ("DomainId") ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS "IX_SeasonDomains_DomainId" ON "SeasonDomains" ("DomainId");
